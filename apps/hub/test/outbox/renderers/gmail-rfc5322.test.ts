import { createHash } from "node:crypto";
import type { ClaimStamp } from "@draftyak/mime";
import { CurrentSendSnapshotV1 } from "@draftyak/protocol/snapshot";
import { describe, expect, it } from "vitest";
import { renderGmailRequest } from "../../../src/outbox/renderers/gmail-rfc5322.ts";
import { nativeSendRenderProjection } from "../../../src/outbox/renderers/native.ts";
import type { RenderedSend } from "../../../src/outbox/ticket-storage.ts";
import { attachment, emailSnapshot } from "./fixture.ts";

const UPLOAD_URL =
	"https://gmail.googleapis.com/upload/gmail/v1/users/me/messages/send?uploadType=multipart";
const digest = (bytes: string | Uint8Array) => createHash("sha256").update(bytes).digest("hex");

function stamp(): ClaimStamp {
	return {
		messageId: "<golden-1.4f2a9c1e@example.com>",
		dateMs: Date.parse("2026-10-17T12:00:00Z"),
		mimeBoundary: "0123456789abcdef01234567",
		uploadBoundary: "draftyak_upload_0123456789abcdef",
	};
}

function input() {
	const base = emailSnapshot();
	const snapshot = CurrentSendSnapshotV1.parse({
		...base,
		body: { text: "Hi Alice,\n\nThursday at noon works for me.\n", footer: "Owner\n" },
		email: {
			from: "owner@example.com",
			to: ["alice@example.org"],
			cc: ["carol@example.net"],
			bcc: [],
			subject: "Re: Lunch on Thursday",
			inReplyTo: "<thread-2@example.org>",
			references: ["<thread-1@example.org>", "<thread-2@example.org>"],
		},
	});
	if (snapshot.kind !== "email") throw new Error("Expected synthetic email");
	return { snapshot, stamp: stamp(), attachments: [] as Uint8Array[] };
}

// The existing pinned ASCII MIME golden, with only display names removed because the frozen
// snapshot contains addresses. No expected bytes are generated by the producer under test.
const ASCII_MIME = Buffer.from(
	[
		"From: owner@example.com",
		"To: alice@example.org",
		"Cc: carol@example.net",
		"In-Reply-To: <thread-2@example.org>",
		"References: <thread-1@example.org> <thread-2@example.org>",
		"Subject: Re: Lunch on Thursday",
		"Message-ID: <golden-1.4f2a9c1e@example.com>",
		"Date: Sat, 17 Oct 2026 12:00:00 +0000",
		"Content-Transfer-Encoding: 7bit",
		"MIME-Version: 1.0",
		"Content-Type: text/plain; charset=utf-8",
		"",
		"Hi Alice,",
		"",
		"Thursday at noon works for me.",
		"",
		"Owner",
		"",
	].join("\r\n"),
);

function unwrap(request: RenderedSend, retained: ClaimStamp, metadata = "{}"): Buffer {
	expect(request.method).toBe("POST");
	expect(request.url).toBe(UPLOAD_URL);
	const contentType = `multipart/related; boundary="${retained.uploadBoundary}"`;
	expect(request.contentType).toBe(contentType);
	expect(request.headers).toEqual([["content-type", contentType]]);
	// Independent complete framing from the existing FakeGmail upload fixture.
	const prefix = Buffer.from(
		`--${retained.uploadBoundary}\r\nContent-Type: application/json; charset=UTF-8\r\n\r\n${metadata}\r\n--${retained.uploadBoundary}\r\nContent-Type: message/rfc822\r\n\r\n`,
	);
	const suffix = Buffer.from(`\r\n--${retained.uploadBoundary}--\r\n`);
	const body = Buffer.from(request.body);
	expect(body.subarray(0, prefix.length)).toEqual(prefix);
	expect(body.subarray(body.length - suffix.length)).toEqual(suffix);
	return body.subarray(prefix.length, body.length - suffix.length);
}

interface Part {
	headers: Map<string, string>;
	mimeType: string;
	filename: string;
	body: Buffer;
	parts: Part[];
}

// Small independent parse-back oracle for these synthetic CRLF fixtures; no provider or IO.
function parse(raw: Buffer): Part {
	const at = raw.indexOf("\r\n\r\n");
	expect(at).toBeGreaterThanOrEqual(0);
	const headers = new Map(
		raw
			.subarray(0, at)
			.toString("latin1")
			.replace(/\r\n(?=[ \t])/g, "")
			.split("\r\n")
			.map((line): [string, string] => {
				const colon = line.indexOf(":");
				return [line.slice(0, colon).toLowerCase(), line.slice(colon + 1).trim()];
			}),
	);
	const type = headers.get("content-type") ?? "text/plain";
	const mimeType = (type.split(";")[0] ?? "").toLowerCase();
	const boundary = /;\s*boundary=(?:"([^"]+)"|([^;\s]+))/i.exec(type);
	const filename = /;\s*filename=(?:"([^"]+)"|([^;\s]+))/i.exec(
		headers.get("content-disposition") ?? "",
	);
	let body = raw.subarray(at + 4);
	if (mimeType.startsWith("multipart/") && boundary) {
		const escaped = (boundary[1] ?? boundary[2] ?? "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
		const parts = body
			.toString("latin1")
			.split(new RegExp(`(?:^|\\r\\n)--${escaped}`))
			.slice(1)
			.filter((piece) => !piece.startsWith("--"))
			.map((piece) => parse(Buffer.from(piece.replace(/^[ \t]*\r\n/, ""), "latin1")));
		return { headers, mimeType, filename: "", body: Buffer.alloc(0), parts };
	}
	const encoding = headers.get("content-transfer-encoding");
	if (encoding === "base64")
		body = Buffer.from(body.toString("latin1").replace(/\s/g, ""), "base64");
	else if (encoding === "quoted-printable") {
		body = Buffer.from(
			body
				.toString("latin1")
				.replace(/=\r\n/g, "")
				.replace(/=([0-9a-f]{2})/gi, (_, hex: string) =>
					String.fromCharCode(Number.parseInt(hex, 16)),
				),
			"latin1",
		);
	}
	return { headers, mimeType, filename: filename?.[1] ?? filename?.[2] ?? "", body, parts: [] };
}

async function refused(raw: unknown) {
	try {
		await renderGmailRequest(raw);
		expect.fail("Expected genuine Gmail wire refusal");
	} catch (error) {
		expect(error).toMatchObject({
			name: "NativeSendRenderError",
			code: "SEND_RENDER_UNAVAILABLE",
			message: "Send rendering unavailable",
		});
		expect(error).not.toHaveProperty("cause");
	}
}

function withAttachments() {
	const base = input();
	const first = Buffer.from("first attachment\n");
	const second = Buffer.from([0, 1, 127, 128, 255, 10]);
	return {
		...base,
		snapshot: {
			...base.snapshot,
			body: { text: "Résumé line 👋", footer: "Footer <literal>\n" },
			attachments: [
				attachment(first, "first.txt"),
				attachment(second, "second.bin", "application/octet-stream"),
			],
		},
		attachments: [first, second],
	};
}

describe("genuine native Gmail multipart wire", () => {
	it("matches the independently pinned ASCII MIME and entire outer-wire hash", async () => {
		const data = input();
		const actual = await renderGmailRequest(data);
		const mime = unwrap(actual, data.stamp);
		expect(ASCII_MIME.byteLength).toBe(432);
		expect(digest(ASCII_MIME)).toBe(
			"c5b70fbe5e372a86f29b43e19b1c4cbe4e2b1bed83e538b0a393936b84ba02ff",
		);
		expect(mime).toEqual(ASCII_MIME);
		expect(actual.body.byteLength).toBe(629);
		expect(nativeSendRenderProjection(actual)).toEqual({
			method: "POST",
			url: UPLOAD_URL,
			headersSha256: "d1d9ca969fd8873017632aef27b69e8e2089f3b8114c72642b78be7ca2d2e430",
			bodySha256: "88a85b171938d61f9299c2af9afc4fe5087453fa215832ded2278c191ac182e4",
		});
		const parsed = parse(mime);
		expect(parsed.headers.get("from")).toBe(data.snapshot.email.from);
		expect(parsed.headers.get("to")).toBe("alice@example.org");
		expect(parsed.headers.get("cc")).toBe("carol@example.net");
		expect(parsed.headers.get("subject")).toBe(data.snapshot.email.subject);
		expect(parsed.headers.get("in-reply-to")).toBe("<thread-2@example.org>");
		expect(parsed.headers.get("references")).toBe("<thread-1@example.org> <thread-2@example.org>");
		expect(parsed.headers.get("message-id")).toBe(data.stamp.messageId);
		expect(Date.parse(parsed.headers.get("date") ?? "")).toBe(data.stamp.dateMs);
		expect(parsed.headers.has("bcc")).toBe(false);
		expect(parsed.body.toString("utf8").replace(/\r\n/g, "\n")).toBe(
			"Hi Alice,\n\nThursday at noon works for me.\n\nOwner\n",
		);
	});

	it("binds the exact frozen thread ID in JSON metadata without changing MIME", async () => {
		const data = input();
		const snapshot = {
			...data.snapshot,
			email: { ...data.snapshot.email, threadId: "thread_123" },
		};
		const actual = await renderGmailRequest({ ...data, snapshot });
		expect(unwrap(actual, data.stamp, '{"threadId":"thread_123"}')).toEqual(ASCII_MIME);
	});

	it("parses back two actual frozen attachment byte sequences in the original order", async () => {
		const data = withAttachments();
		const before = data.attachments.map((bytes) => Buffer.from(bytes));
		const actual = await renderGmailRequest(data);
		const parsed = parse(unwrap(actual, data.stamp));
		expect(parsed.mimeType).toBe("multipart/mixed");
		expect(parsed.parts).toHaveLength(3);
		expect(parsed.parts[0]?.body.toString("utf8").replace(/\r\n/g, "\n")).toBe(
			"Résumé line 👋\nFooter <literal>\n",
		);
		for (const [index, expected] of before.entries()) {
			expect(parsed.parts[index + 1]?.filename).toBe(data.snapshot.attachments[index]?.filename);
			expect(parsed.parts[index + 1]?.mimeType).toBe(data.snapshot.attachments[index]?.contentType);
			expect(parsed.parts[index + 1]?.body).toEqual(expected);
			expect(data.attachments[index]).toEqual(expected);
		}
	});

	it("is repeatable with the same retained stamp and owns detached result bytes", async () => {
		const data = withAttachments();
		const first = await renderGmailRequest(data);
		const second = await renderGmailRequest(data);
		expect(first).toEqual(second);
		const kept = Buffer.from(second.body);
		first.body.fill(0);
		expect(Buffer.from(second.body)).toEqual(kept);
		expect(second.body).not.toBe(first.body);
	});

	it.each(["messageId", "dateMs", "mimeBoundary", "uploadBoundary"] as const)(
		"changes real request bytes when retained stamp %s changes",
		async (field) => {
			const data = withAttachments();
			const changed = {
				...data.stamp,
				[field]:
					field === "dateMs"
						? data.stamp.dateMs + 1000
						: field === "messageId"
							? "<another-claim@example.com>"
							: field === "mimeBoundary"
								? "abcdef0123456789abcdef01"
								: "different_upload_0123456789abcdef",
			};
			const original = await renderGmailRequest(data);
			const actual = await renderGmailRequest({ ...data, stamp: changed });
			expect(digest(actual.body)).not.toBe(digest(original.body));
		},
	);

	it("refuses Bcc through the real MIME policy without dropping its frozen recipients", async () => {
		const data = input();
		const snapshot = {
			...data.snapshot,
			email: { ...data.snapshot.email, bcc: ["hidden@example.test"] },
		};
		await refused({ ...data, snapshot });
		expect(snapshot.email.bcc).toEqual(["hidden@example.test"]);
	});

	it.each(["count", "size", "hash", "order"] as const)(
		"refuses actual attachment %s mismatch at the public Gmail entry",
		async (fault) => {
			const data = withAttachments();
			const attachments =
				fault === "count"
					? data.attachments.slice(1)
					: fault === "size"
						? [Buffer.from("short"), data.attachments[1]]
						: fault === "hash"
							? [Buffer.from("other attachment\n"), data.attachments[1]]
							: [...data.attachments].reverse();
			await refused({ ...data, attachments });
		},
	);

	it("refuses a shared attachment backing with matching frozen bytes", async () => {
		const data = input();
		await refused({
			...data,
			snapshot: { ...data.snapshot, attachments: [attachment(new Uint8Array(3))] },
			attachments: [new Uint8Array(new SharedArrayBuffer(3))],
		});
	});

	it("refuses actual attachment bytes above the native bound before composition", async () => {
		const data = input();
		const bytes = new Uint8Array(33_554_433);
		await refused({
			...data,
			snapshot: {
				...data.snapshot,
				attachments: [attachment(bytes, "large.bin", "application/octet-stream")],
			},
			attachments: [bytes],
		});
	});

	it("refuses an upload-boundary delimiter present in genuine MIME text", async () => {
		const data = input();
		await refused({
			...data,
			snapshot: {
				...data.snapshot,
				body: { text: `Unsafe --${data.stamp.uploadBoundary} delimiter\n`, footer: "" },
			},
		});
	});

	it("rejects a source-header injection without silently sanitizing the frozen subject", async () => {
		const data = input();
		await refused({
			...data,
			snapshot: {
				...data.snapshot,
				email: { ...data.snapshot.email, subject: "Subject\r\nX-Other: injected" },
			},
		});
	});

	it.each(["accessor", "proxy"] as const)(
		"refuses a hostile outer %s without executing it",
		async (fault) => {
			let calls = 0;
			const data = input();
			const getter = () => {
				calls++;
				throw new Error("Untrusted source detail");
			};
			const raw =
				fault === "accessor"
					? Object.defineProperty(data, "snapshot", { enumerable: true, get: getter })
					: new Proxy(data, { get: getter, ownKeys: getter });
			await refused(raw);
			expect(calls).toBe(0);
		},
	);
});
